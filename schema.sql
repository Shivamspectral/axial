-- Useful analytics view. security_invoker keeps RLS from being bypassed.
create or replace view public.axial_feedback_summary
with (security_invoker=true)
as
select
  f.cycle_id,
  f.faculty_id,
  vf.full_name as faculty_name,
  vf.department_code,
  count(distinct f.id) as submissions,
  round(avg(a.rating)::numeric,2) as average_rating
from public.axial_v3_feedback f
join public.axial_v3_faculty vf on vf.id=f.faculty_id
left join public.axial_v3_feedback_answers a on a.feedback_id=f.id
where a.rating is not null
group by f.cycle_id,f.faculty_id,vf.full_name,vf.department_code;

