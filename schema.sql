-- ASTRA / Siddhant College of Engineering Feedback Intelligence
-- Production schema for student ID-only feedback, HOD analytics, and Super Admin control.

create extension if not exists pgcrypto;

create table if not exists public.axial_students (
  id bigint generated by default as identity primary key,
  student_id text not null unique,
  full_name text not null,
  department_code text not null,
  year_level text not null check (year_level in ('SE','TE','BE','FE')),
  division text not null,
  academic_year text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.axial_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_role text,
  action text not null,
  entity text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists axial_students_department_idx on public.axial_students(department_code);
create index if not exists axial_students_active_idx on public.axial_students(active);
create index if not exists axial_feedback_cycle_idx on public.axial_v3_feedback(cycle_id);
