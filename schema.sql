-- Student feedback submission policy: use fully-qualified outer-row references.
drop policy if exists feedback_student_insert on public.axial_v3_feedback;
create policy feedback_student_insert
on public.axial_v3_feedback
for insert to anon, authenticated
with check (
  student_login_id = (coalesce(current_setting('request.headers', true), '{}')::jsonb ->> 'x-student-id')
  and exists (
    select 1 from public.axial_students s
    where s.student_id = axial_v3_feedback.student_login_id
      and s.active = true
      and s.year_level = axial_v3_feedback.year_level
      and s.division = axial_v3_feedback.division
  )
  and exists (
    select 1 from public.axial_v3_cycles c
    where c.id = axial_v3_feedback.cycle_id
      and c.status = 'open'
      and current_date between c.start_date and c.end_date
      and c.year_level = axial_v3_feedback.year_level
  )
  and exists (
    select 1 from public.axial_v3_faculty f
    where f.id = axial_v3_feedback.faculty_id
      and f.active = true
      and f.year_level = axial_v3_feedback.year_level
      and f.division = axial_v3_feedback.division
  )
  and exists (
    select 1 from public.axial_v3_cycle_faculty cf
    where cf.cycle_id = axial_v3_feedback.cycle_id
      and cf.faculty_id = axial_v3_feedback.faculty_id
      and cf.division = axial_v3_feedback.division
  )
  and not exists (
    select 1 from public.axial_v3_feedback old
    where old.cycle_id = axial_v3_feedback.cycle_id
      and old.faculty_id = axial_v3_feedback.faculty_id
      and old.student_login_id = axial_v3_feedback.student_login_id
  )
);
