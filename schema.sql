create index if not exists axial_answers_feedback_idx on public.axial_v3_feedback_answers(feedback_id);

-- Profiles are the authorization source for staff roles. Do not use user-editable metadata for authorization.
create or replace function public.is_staff_role(required_role text)
returns boolean
language sql
stable
security invoker
as $$
  select exists (
    select 1 from public.profiles p
    where p.user_id = (select auth.uid())::text
      and p.role = required_role
  );
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
security invoker
as $$
  select exists (
    select 1 from public.profiles p
    where p.user_id = (select auth.uid())::text
      and p.role = 'Super Admin'
  );
$$;

create or replace function public.is_hod()
returns boolean
language sql
stable
security invoker
as $$
  select exists (
    select 1 from public.profiles p
    where p.user_id = (select auth.uid())::text
      and p.role = 'HOD'
  );
$$;

