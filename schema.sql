-- Students submit anonymously by ID. The database verifies the ID, active student, open cycle,
-- matching year/division, and prevents duplicate submission for a student/cycle/faculty pair.
create or replace function public.submit_feedback(
  p_cycle_id bigint,
  p_faculty_id bigint,
  p_student_id text,
  p_year_level text,
  p_division text,
  p_comment text,
  p_answers jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student public.axial_students%rowtype;
  v_cycle public.axial_v3_cycles%rowtype;
  v_feedback_id bigint;
  a jsonb;
begin
  select * into v_student from public.axial_students
  where student_id = p_student_id and active = true limit 1;
  if not found then raise exception 'Invalid or inactive student ID'; end if;

  if v_student.year_level <> p_year_level or v_student.division <> p_division then
    raise exception 'Student academic mapping does not match the selected feedback context';
  end if;

  select * into v_cycle from public.axial_v3_cycles where id = p_cycle_id and status='open';
  if not found then raise exception 'Feedback cycle is not open'; end if;

  if current_date < v_cycle.start_date or current_date > v_cycle.end_date then
    raise exception 'Feedback cycle is outside its active date window';
  end if;

  if exists (
    select 1 from public.axial_v3_feedback
    where cycle_id=p_cycle_id and faculty_id=p_faculty_id and student_login_id=p_student_id
  ) then raise exception 'Feedback already submitted for this faculty'; end if;

  insert into public.axial_v3_feedback(cycle_id, faculty_id, student_login_id, student_id, year_level, division, comment)
  values(p_cycle_id,p_faculty_id,p_student_id,p_student_id,p_year_level,p_division,nullif(trim(p_comment),''))
  returning id into v_feedback_id;

  for a in select * from jsonb_array_elements(coalesce(p_answers,'[]'::jsonb)) loop
    insert into public.axial_v3_feedback_answers(feedback_id,question_id,rating,yes_no,text_response)
    values(
      v_feedback_id,
      (a->>'question_id')::bigint,
      nullif(a->>'rating','')::numeric,
      case when a ? 'yes_no' then (a->>'yes_no')::boolean else null end,
      nullif(a->>'text_response','')
    );
  end loop;
  return v_feedback_id;
end;
$$;

revoke all on function public.submit_feedback(bigint,bigint,text,text,text,text,jsonb) from public;
